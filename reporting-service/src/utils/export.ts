// ─── Public API ─────────────────────────────────────────────────────────────

export function sendReport(res: Response, meta: ReportExportMeta, format: ExportFormat) {
  if (format === 'csv') {
    const csv = buildBusinessCsv(meta);
    res.setHeader('Content-Type', 'text/csv; charset=utf-8');
    res.setHeader('Content-Disposition', `attachment; filename="${slug(meta.title)}-${dateSlug()}.csv"`);
    return res.send('\uFEFF' + csv);
  }

  if (format === 'pdf') {
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename="${slug(meta.title)}-${dateSlug()}.pdf"`);
    const doc = new PDFDocument({ margin: 48, size: 'A4', bufferPages: true });
    doc.pipe(res);
    buildBusinessPdf(doc, meta);
    doc.end();
    return;
  }

  return res.json({ success: true, data: meta.data });
}

export function parseFormat(q: unknown): ExportFormat {
  const f = String(q || 'json').toLowerCase();
  if (f === 'csv' || f === 'pdf') return f;
  return 'json';
}

export function groupByPeriod(items: { createdAt?: string; installationDate?: string }[], dateField: 'createdAt' | 'installationDate') {
  const now = new Date();
  const today = startOfDay(now);
  const monthStart = new Date(now.getFullYear(), now.getMonth(), 1);
  const yearStart = new Date(now.getFullYear(), 0, 1);

  let daily = 0, monthly = 0, yearly = 0;
  for (const item of items) {
    const raw = item[dateField];
    if (!raw) continue;
    const d = startOfDay(new Date(raw));
    if (d.getTime() === today.getTime()) daily++;
    if (d >= monthStart) monthly++;
    if (d >= yearStart) yearly++;
  }
  return { daily, monthly, yearly };
}

/** @deprecated use buildBusinessCsv paths */
export function toCsvRows(data: unknown): Record<string, unknown>[] {
  if (Array.isArray(data)) return data as Record<string, unknown>[];
  if (data && typeof data === 'object') {
    const obj = data as Record<string, unknown>;
    if (Array.isArray(obj.items)) return obj.items as Record<string, unknown>[];
    return [obj];
  }
  return [{ value: data }];
}

// ─── CSV ────────────────────────────────────────────────────────────────────

function buildBusinessCsv(meta: ReportExportMeta): string {
  const lines: string[] = [];
  const generatedAt = extractGeneratedAt(meta.data);

  lines.push(...csvHeaderBlock(meta.title, generatedAt));

  switch (meta.kind) {
    case 'inventory':
      lines.push(...csvInventory(meta.data as InventoryData));
      break;
    case 'inspection-status':
      lines.push(...csvInspectionStatus(meta.data as InspectionStatusData));
      break;
    case 'inspection-list':
      lines.push(...csvInspectionList(meta.data));
      break;
    case 'expired':
      lines.push(...csvExtinguisherList('Expired Extinguishers', meta.data));
      break;
    case 'maintenance':
      lines.push(...csvMaintenance(meta.data as MaintenanceData));
      break;
    case 'compliance':
      lines.push(...csvCompliance(meta.data as ComplianceData));
      break;
    case 'maintenance-frequency':
      lines.push(...csvMaintenanceFrequency(meta.data as MaintenanceFrequencyData));
      break;
    default:
      lines.push(...csvGeneric(meta.data));
      break;
  }

  lines.push('');
  lines.push(...csvTableBlock('Document Footer', [
    { key: 'note', label: 'Note' },
  ], [
    { note: `Report generated by ${BRAND.company} ${BRAND.system}` },
    { note: 'Confidential — For internal business use only' },
  ]));

  return lines.join('\r\n');
}

/** Exposed for unit tests */
export function buildBusinessCsvPreview(meta: ReportExportMeta): string {
  return '\uFEFF' + buildBusinessCsv(meta);
}

function csvHeaderBlock(title: string, generatedAt: string | null): string[] {
  const when = generatedAt ? formatDisplayDate(generatedAt) : formatDisplayDate(new Date().toISOString());
  return csvTableBlock('Report Information', [
    { key: 'field', label: 'Field' },
    { key: 'value', label: 'Value' },
  ], [
    { field: 'Organization', value: `${BRAND.company} — ${BRAND.system}` },
    { field: 'Report Title', value: title },
    { field: 'Generated', value: when },
  ]);
}

function escapeCsvCell(value: unknown): string {
  const s = value == null || value === '' ? '—' : String(value);
  if (/[",\r\n]/.test(s)) {
    return `"${s.replace(/"/g, '""')}"`;
  }
  return s;
}

function csvTableBlock(
  sectionTitle: string,
  columns: { key: string; label: string }[],
  rows: Record<string, string>[],
): string[] {
  const lines: string[] = [];
  const width = Math.max(columns.length, 1);

  lines.push([
    escapeCsvCell(sectionTitle),
    ...Array.from({ length: width - 1 }, () => ''),
  ].join(','));

  lines.push(columns.map((c) => escapeCsvCell(c.label)).join(','));

  if (rows.length === 0) {
    lines.push(columns.map(() => escapeCsvCell('—')).join(','));
  } else {
    for (const row of rows) {
      lines.push(columns.map((c) => escapeCsvCell(row[c.key] ?? '—')).join(','));
    }
  }

  lines.push('');
  return lines;
}

function csvKeyValueSection(title: string, pairs: { label: string; value: string | number }[]): string[] {
  return csvTableBlock(
    title,
    [{ key: 'metric', label: 'Metric' }, { key: 'value', label: 'Value' }],
    pairs.map((p) => ({ metric: p.label, value: String(p.value) })),
  );
}

function csvSection(title: string, rows: Record<string, string>[], columns: { key: string; label: string }[]): string[] {
  return csvTableBlock(title, columns, rows);
}

