function csvInspectionList(data: unknown): string[] {
  const items = Array.isArray(data)
    ? data
    : data && typeof data === 'object' && Array.isArray((data as { items?: unknown[] }).items)
      ? (data as { items: Record<string, unknown>[] }).items
      : [];

  const rows = items.map(flattenInspection);
  const lines = csvKeyValueSection('Executive Summary', [
    { label: 'Total Inspections', value: rows.length },
  ]);
  lines.push(...csvSection('Inspection Detail', rows, INSPECTION_COLUMNS));
  return lines;
}

